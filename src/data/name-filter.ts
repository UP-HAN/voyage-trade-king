/**
 * 회사 이름 금칙어 기본 목록 (PRD 6.1.1, v0.3.1) — 작업 124 소유 데이터.
 *
 * - 교사·운영자가 낱말을 더하거나 뺄 수 있다(이 파일을 고치거나, 판 설정의 '추가 금칙어'(P1)로 더함).
 * - 여기 낱말은 **화면에 보여 주지 않는다**. 걸리면 "회사 이름으로 쓸 수 없는 말이 있어요. 다른 이름을 지어요."만 보여 준다.
 * - 검사는 `src/sync/company-name.ts`가 한다: 비교 키(공백 제거 + 영문 소문자 + NFC)와,
 *   비교 키에서 숫자·영문을 뺀 키 두 가지에 대해 **부분 문자열**로 찾는다. 그래서 평범한 낱말 속에 잘 섞이는 말
 *   (예: 바다·무지개 같은 낱말과 겹치는 짧은 조각)은 넣지 않는다. 영문 낱말은 소문자로 적는다(예: 'kill'은 'skill'과 겹쳐 뺐다).
 * - (작업 132, 수정 2회차) 부분 일치 오탐 예외는 **명시한 것만**: ① 금칙어가 평범한 낱말(`allowWords`) 안에 통째로 들어 있을 때
 *   (예: '시발점' ⊃ '시발') ② 허용 조합(`allowJoins`) — 앞 낱말 끝과 금칙어 앞부분이 겹치고 금칙어 뒷부분이 **정해진 다음 낱말**로
 *   이어질 때만(예: 햇살 + 해운 → '햇살해운'의 '살해'). 일반 겹침 규칙은 없다. 원칙: 확신이 없으면 막는다(교사가 이름을 바꿔 줄 수 있음).
 * - (작업 134) 변형 잡기: 늘여 쓴 말('시이발' → '시발', 같은 모음을 'ㅇ+모음' 글자로 한 번 더 쓴 것을 줄임)과
 *   영문 숫자 바꿔 쓰기('sh1t' → 'shit', 0→o 1→i 3→e 4→a 5→s 7→t)도 검사 키로 본다.
 * - 초등 교실에서 흔한 욕설·비하·놀림 말 중심. 낱말을 지나치게 넓게 잡으면 평범한 회사 이름이 막히므로,
 *   더할 때는 다른 낱말 속에 잘 섞이지 않는 2자 이상 표현을 고른다.
 * - 쪽수 검사(check:data) 대상이 아니다.
 */

export interface NameFilterData {
  version: number;
  categories: {
    /** 욕설 */
    profanity: string[];
    /** 비하(장애·성별·외모·지역·인종·가족) */
    slur: string[];
    /** 성적 표현 */
    sexual: string[];
    /** 폭력·자해 */
    violence: string[];
    /** 놀림 말 */
    teasing: string[];
  };
  patterns: {
    /** 개인정보 형태(정규식 문자열, 대소문자 무시로 검사) */
    personalInfo: string[];
  };
  /** 회사 낱말 — 이 낱말이 있으면 '사람 이름처럼 보여요' 안내를 하지 않는다. 한 글자 낱말(예: 호)은 이름 끝에 올 때만 본다 */
  companyWords: string[];
  /** 흔한 성씨(한 글자) — '사람 이름처럼 보여요' 판단용 */
  commonSurnames: string[];
  /** (작업 132) 금칙어를 통째로 품은 평범한 낱말 — 이 낱말 안에 들어 있는 금칙어 일치는 오탐으로 본다(예: 시발점) */
  allowWords?: string[];
  /** (작업 132 수정 2회차) 허용 조합 — `word` + `next` 낱말이 이어진 자리에 걸친 금칙어 `bad`만 오탐으로 본다 */
  allowJoins?: { word: string; bad: string; next: string[] }[];
}

